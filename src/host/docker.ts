// Compose file generation and container lifecycle. Every Docker call is argv-only (no shell).
import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MinionsError } from '../core/errors.js';
import { run, type RunOptions, type RunResult } from '../core/exec.js';
import { CONTAINER, SERVICE_NAME, composeProjectName, projectPaths, volumeNames } from '../core/paths.js';
import type { ProjectJson } from './project.js';

export type Runner = (cmd: string, args: string[], opts?: RunOptions) => Promise<RunResult>;

const q = (s: string | number) => JSON.stringify(String(s)); // JSON strings are valid YAML scalars

/**
 * Generates compose.yaml for one project. Security baseline (spec §3A, bootstrap "Container"):
 * non-root, read-only rootfs, all caps dropped, no-new-privileges, resource limits, tmpfs for /tmp
 * and /home/node, named volumes for state, ro binds only for the plugin, runtime config and secrets dir,
 * loopback-only published ports, no Docker socket, no privileged mode, no host network/PID.
 */
export function composeYaml(p: ProjectJson): string {
  const paths = projectPaths(p.projectId);
  const vols = volumeNames(p.projectId);
  const c = p.container;
  const L: string[] = [
    '# Generated by minions. Host-controlled: the container cannot modify this file.',
    `name: ${q(composeProjectName(p.projectId))}`,
    'services:',
    `  ${SERVICE_NAME}:`,
    `    image: ${q(p.imageTag)}`,
    '    pull_policy: never',
    '    user: "1000:1000"',
    '    init: true',
    '    read_only: true',
    '    privileged: false',
    '    cap_drop: ["ALL"]',
    '    security_opt: ["no-new-privileges:true"]',
    `    cpus: ${c.cpus}`,
    `    mem_limit: ${q(`${c.memoryMiB}m`)}`,
    `    pids_limit: ${c.pidsLimit}`,
    ...(c.network === 'none' ? ['    network_mode: "none"'] : []),
    '    command: ["sleep", "infinity"]',
    `    working_dir: ${q(CONTAINER.workspace)}`,
    '    environment:',
    '      MINIONS_RUNTIME: "container"',
    `      CLAUDE_CONFIG_DIR: ${q(CONTAINER.claudeHome)}`,
    `      MINIONS_CONFIG: ${q(CONTAINER.configJson)}`,
    '      HOME: "/home/node"',
    // Claude Code's TUI runs inside tmux: it needs a UTF-8 locale (C.UTF-8 ships with Debian) and a color TERM.
    '      LANG: "C.UTF-8"',
    '      LC_ALL: "C.UTF-8"',
    '      TERM: "xterm-256color"',
    '      npm_config_cache: "/home/node/.cache/npm"',
    '      XDG_CACHE_HOME: "/home/node/.cache"',
    // Bun (Telegram plugin dependencies) caches in the cache volume; /home/node itself is tmpfs.
    '      BUN_INSTALL_CACHE_DIR: "/home/node/.cache/bun"',
    '    tmpfs:',
    '      - "/tmp:rw,nosuid,nodev,uid=1000,gid=1000,mode=1777"',
    '      - "/home/node:rw,nosuid,nodev,uid=1000,gid=1000,mode=0755"',
    '    volumes:',
  ];
  const vol = (source: string, target: string) => L.push(
    '      - type: volume', `        source: ${source}`, `        target: ${q(target)}`);
  vol('workspace', CONTAINER.workspace);
  vol('state', CONTAINER.state);
  vol('claude', CONTAINER.claudeHome);
  vol('cache', CONTAINER.cache);
  const bind = (source: string, target: string) => L.push(
    '      - type: bind', `        source: ${q(source)}`, `        target: ${q(target)}`, '        read_only: true',
    '        bind:', '          create_host_path: false');
  bind(paths.pluginDir, CONTAINER.pluginDir);
  bind(paths.runtimeDir, CONTAINER.configDir);
  // Secrets: a directory mount (never a single-file mount) so a token replaced on the host via
  // rename (new inode) is visible without recreating the container. Only materialized secret files
  // live here; the host credential store (Keychain / credentials dir) is never mounted.
  bind(paths.secretsDir, CONTAINER.secretsDir);
  if (c.publishPorts.length && c.network !== 'none') {
    L.push('    ports:');
    for (const { host, container } of c.publishPorts) L.push(`      - ${q(`127.0.0.1:${host}:${container}`)}`);
  }
  L.push('volumes:');
  for (const [key, name] of Object.entries(vols)) L.push(`  ${key}:`, `    name: ${q(name)}`);
  return L.join('\n') + '\n';
}

/** Package root (directory with package.json named "minions"), resolved from the running CLI file. */
export function packageRoot(from: string = fileURLToPath(import.meta.url)): string {
  let dir = dirname(from);
  for (;;) {
    const pj = join(dir, 'package.json');
    if (existsSync(pj)) {
      try { if ((JSON.parse(readFileSync(pj, 'utf8')) as { name?: string }).name === 'minions') return dir; } catch { /* keep walking */ }
    }
    const up = dirname(dir);
    if (up === dir) throw new MinionsError('INTERNAL', 'Cannot locate the minions package root.', 'Reinstall minions.');
    dir = up;
  }
}

export class Compose {
  constructor(readonly projectId: string, private readonly runner: Runner = run) {}

  get name() { return composeProjectName(this.projectId); }
  get file() { return projectPaths(this.projectId).composeYaml; }
  argv(...args: string[]): string[] { return ['compose', '-p', this.name, '-f', this.file, ...args]; }

  compose(args: string[], opts: RunOptions = {}): Promise<RunResult> {
    return this.runner('docker', this.argv(...args), { timeoutMs: 300_000, ...opts });
  }

  async up(): Promise<void> { await this.compose(['up', '-d', '--no-build', '--remove-orphans']); }
  async down(opts: { volumes?: boolean } = {}): Promise<void> { await this.compose(['down', ...(opts.volumes ? ['-v'] : [])]); }

  async isRunning(): Promise<boolean> {
    const r = await this.compose(['ps', '--status', 'running', '-q', SERVICE_NAME], { allowFailure: true, timeoutMs: 30_000 });
    return r.code === 0 && r.stdout.trim().length > 0;
  }

  /** Non-interactive exec (no TTY); output captured. */
  exec(args: string[], opts: RunOptions = {}): Promise<RunResult> {
    return this.compose(['exec', '-T', SERVICE_NAME, ...args], opts);
  }

  /** Exec with inherited stdio. `tty` allocates a pseudo-TTY (interactive sessions). Returns exit code. */
  execInherit(args: string[], opts: { tty: boolean }): Promise<number> {
    const argv = this.argv('exec', ...(opts.tty ? [] : ['-T']), SERVICE_NAME, ...args);
    return new Promise((resolve, reject) => {
      const child = spawn('docker', argv, { stdio: 'inherit', shell: false });
      child.on('error', (e: NodeJS.ErrnoException) => reject(e.code === 'ENOENT'
        ? new MinionsError('DOCKER_UNAVAILABLE', 'docker CLI not found.', 'Install and start Docker Desktop.') : e));
      child.on('close', (code, signal) => resolve(code ?? (signal ? 128 : 1)));
    });
  }

  async cp(src: string, dst: string): Promise<void> { await this.compose(['cp', src, dst]); }
}

export const BUILD_LABEL = 'minions.build';

export async function imageExists(tag: string, runner: Runner = run): Promise<boolean> {
  return (await imageBuildLabel(tag, runner)) !== null;
}

/** The image's `minions.build` label ('' when unlabeled), or null when the image is missing. */
export async function imageBuildLabel(tag: string, runner: Runner = run): Promise<string | null> {
  const r = await runner('docker', ['image', 'inspect', '--format', `{{index .Config.Labels "${BUILD_LABEL}"}}`, tag], { allowFailure: true, timeoutMs: 30_000 });
  if (r.code !== 0) return null;
  const v = r.stdout.trim();
  return v === '<no value>' ? '' : v;
}

/** Fingerprint of what goes into the image from the package (null when dist/ is not built). */
export function buildFingerprint(root: string = packageRoot()): string | null {
  const files = [join('dist', 'cli.js'), join('docker', 'Dockerfile'), join('docker', 'gh-wrapper.sh'), 'package.json'];
  if (!existsSync(join(root, files[0]!))) return null;
  const h = createHash('sha256');
  for (const f of files) h.update(f).update('\0').update(existsSync(join(root, f)) ? readFileSync(join(root, f)) : '').update('\0');
  return h.digest('hex').slice(0, 16);
}

/**
 * Builds `tag` from the package root with docker/Dockerfile when missing, or when its build label
 * does not match the installed package (same version reinstalled with different code). Returns true if built.
 */
export async function ensureImage(tag: string, opts: { runner?: Runner; root?: string; onBuild?: (msg: string) => void } = {}): Promise<boolean> {
  const runner = opts.runner ?? run;
  const root = opts.root ?? packageRoot();
  const label = await imageBuildLabel(tag, runner);
  const fp = buildFingerprint(root);
  if (label !== null && (fp === null || label === fp)) return false;
  if (fp === null) {
    throw new MinionsError('PRECONDITION', `Package at ${root} has no dist/cli.js; cannot build the runtime image.`, 'Run `npm run build` in the minions package.');
  }
  opts.onBuild?.(label === null
    ? `Building image ${tag} from ${root} (first run may take a few minutes)…`
    : `Rebuilding image ${tag}: the installed package changed since it was built…`);
  await runner('docker', ['build', '-t', tag, '--label', `${BUILD_LABEL}=${fp}`, '-f', join(root, 'docker', 'Dockerfile'), root], { timeoutMs: 1_800_000 });
  return true;
}
