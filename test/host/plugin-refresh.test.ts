// task-46: the plugin the container mounts (<project dir>/plugin) follows the installed package.
// `refreshDerived` (used by `minions start` and the upgrade's files step) regenerates it from the
// templates of the package that runs; `checkPlugin` / the doctor check report a plugin that differs.
// Templates are switched with MINIONS_TEMPLATES to stand for an old and a new installed package.
import { appendFileSync, cpSync, existsSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { projectPaths } from '../../src/core/paths.js';
import { pluginDoctorCheck } from '../../src/host/doctor.js';
import { checkPlugin, pluginMismatch, refreshDerived, runInit } from '../../src/host/install.js';
import { loadEffectiveConfig, loadProjectJson } from '../../src/host/project.js';
import { dockerUp, makeRepo, tempDir, withHome } from './fixtures.js';

const TEMPLATES = join(import.meta.dirname, '..', '..', 'templates');
const NEW_LINE = 'NEW PACKAGE: hand results off with `minions work submit`.';

/** A templates root (containing plugin/) copied from this checkout. */
function packageTemplates(prefix: string): string {
  const dir = tempDir(prefix);
  cpSync(join(TEMPLATES, 'plugin'), join(dir, 'plugin'), { recursive: true });
  return dir;
}

let home: ReturnType<typeof withHome>;
let prevTemplates: string | undefined;
let oldPkg: string, newPkg: string;
beforeEach(() => {
  home = withHome();
  prevTemplates = process.env.MINIONS_TEMPLATES;
  oldPkg = packageTemplates('minions-old-pkg-');
  newPkg = packageTemplates('minions-new-pkg-');
  // The new package changed a worker definition and the coordinator prompt, added a skill and dropped one.
  appendFileSync(join(newPkg, 'plugin', 'agents', 'engineer.md'), `\n${NEW_LINE}\n`);
  appendFileSync(join(newPkg, 'plugin', 'coordinator.md'), `\n${NEW_LINE}\n`);
  cpSync(join(newPkg, 'plugin', 'skills', 'status'), join(newPkg, 'plugin', 'skills', 'added'), { recursive: true });
  rmSync(join(newPkg, 'plugin', 'skills', 'maintain-context'), { recursive: true });
});
afterEach(() => {
  if (prevTemplates === undefined) delete process.env.MINIONS_TEMPLATES; else process.env.MINIONS_TEMPLATES = prevTemplates;
  for (const d of [oldPkg, newPkg]) rmSync(d, { recursive: true, force: true });
  home.cleanup();
});

/** `minions init` with the old package installed. */
async function initOld() {
  process.env.MINIONS_TEMPLATES = oldPkg;
  const repo = makeRepo(home.root);
  const r = await runInit({ path: repo, yes: true, visibility: 'private', dockerProbe: dockerUp });
  const project = await loadProjectJson(r.plan.projectId);
  const config = (await loadEffectiveConfig(project)).config;
  return { project, config, dir: projectPaths(project.projectId).pluginDir };
}

describe('plugin refresh from the installed package', () => {
  it('a plugin generated by an older package is reported stale, then regenerated in place by refreshDerived', async () => {
    const { project, config, dir } = await initOld();
    expect(readFileSync(join(dir, 'agents', 'engineer.md'), 'utf8')).not.toContain(NEW_LINE);
    const ino = statSync(dir).ino;

    process.env.MINIONS_TEMPLATES = newPkg; // the CLI now runs from the new package
    const before = await checkPlugin(project, config);
    expect(before.matches).toBe(false);
    expect(before.differs).toEqual(expect.arrayContaining(['coordinator.md', join('agents', 'engineer.md'), join('agents', 'engineer-deep.md')]));
    expect(before.missing).toEqual([join('skills', 'added', 'SKILL.md')]);
    expect(before.extra).toEqual([join('skills', 'maintain-context', 'SKILL.md')]);
    expect(pluginMismatch(before)).toMatch(/file\(s\) differ from the installed package .*coordinator\.md/);
    expect(pluginDoctorCheck(before)).toMatchObject({ name: 'plugin', status: 'warn', hint: expect.stringContaining('minions upgrade') });

    expect(await refreshDerived(project, config)).toEqual([]);
    expect(readFileSync(join(dir, 'agents', 'engineer.md'), 'utf8')).toContain(NEW_LINE);
    expect(readFileSync(join(dir, 'coordinator.md'), 'utf8')).toContain(NEW_LINE);
    expect(existsSync(join(dir, 'skills', 'added', 'SKILL.md'))).toBe(true);
    expect(existsSync(join(dir, 'skills', 'maintain-context', 'SKILL.md'))).toBe(false); // unchanged and no longer generated
    // Files are replaced inside the directory; the directory itself (the bind-mount source) stays the same inode.
    expect(statSync(dir).ino).toBe(ino);
    const after = await checkPlugin(project, config);
    expect(after).toMatchObject({ matches: true, differs: [], missing: [], extra: [] });
    expect(pluginMismatch(after)).toBeNull();
    expect(pluginDoctorCheck(after)).toMatchObject({ name: 'plugin', status: 'ok' });

    // The manifest tracks the new files, so a later refresh is a no-op and uninstall knows them.
    const manifest = JSON.parse(readFileSync(projectPaths(project.projectId).manifestJson, 'utf8')) as { files: { path: string }[] };
    const tracked = manifest.files.map((f) => f.path);
    expect(tracked).toContain(join(dir, 'skills', 'added', 'SKILL.md'));
    expect(tracked).not.toContain(join(dir, 'skills', 'maintain-context', 'SKILL.md'));
    expect(await refreshDerived(project, config)).toEqual([]);
  });

  it('keeps a plugin file the user edited (warning) and the check keeps reporting it', async () => {
    const { project, config, dir } = await initOld();
    writeFileSync(join(dir, 'coordinator.md'), 'my own coordinator\n');
    process.env.MINIONS_TEMPLATES = newPkg;
    const warnings = await refreshDerived(project, config);
    expect(warnings).toEqual([`${join(dir, 'coordinator.md')} was edited since generation; using it as is.`]);
    expect(readFileSync(join(dir, 'coordinator.md'), 'utf8')).toBe('my own coordinator\n');
    expect(readFileSync(join(dir, 'agents', 'engineer.md'), 'utf8')).toContain(NEW_LINE);
    const c = await checkPlugin(project, config);
    expect(c).toMatchObject({ matches: false, differs: ['coordinator.md'], missing: [], extra: [] });
    expect(pluginDoctorCheck(c, true).hint).toContain('minions down && minions start');
  });

  it('keeps an edited file the new package no longer generates (warning), and still reports it as extra', async () => {
    const { project, config, dir } = await initOld();
    const gone = join(dir, 'skills', 'maintain-context', 'SKILL.md');
    writeFileSync(gone, 'my skill\n');
    process.env.MINIONS_TEMPLATES = newPkg;
    const warnings = await refreshDerived(project, config);
    expect(warnings).toEqual([`${gone} is no longer generated but was edited; left in place.`]);
    expect(readFileSync(gone, 'utf8')).toBe('my skill\n');
    expect((await checkPlugin(project, config)).extra).toEqual([join('skills', 'maintain-context', 'SKILL.md')]);
  });

  it('refresh recreates a missing or partially written plugin dir; the check reports it without throwing', async () => {
    const { project, config, dir } = await initOld();
    process.env.MINIONS_TEMPLATES = newPkg;
    rmSync(dir, { recursive: true, force: true });
    const c = await checkPlugin(project, config);
    expect(c.matches).toBe(false);
    expect(c.missing.length).toBe(c.files);
    expect(c.extra).toEqual([]);
    expect(await refreshDerived(project, config)).toEqual([]);
    expect((await checkPlugin(project, config)).matches).toBe(true);
    // Partially written: one file and a whole subdirectory gone.
    rmSync(join(dir, 'agents', 'engineer.md'));
    rmSync(join(dir, 'skills'), { recursive: true });
    expect((await checkPlugin(project, config)).missing).toContain(join('agents', 'engineer.md'));
    expect(await refreshDerived(project, config)).toEqual([]);
    expect((await checkPlugin(project, config)).matches).toBe(true);
  });

  it('the doctor check reports a comparison failure as a warning, not a crash', () => {
    expect(pluginDoctorCheck(new Error('Plugin templates not found at /x'))).toMatchObject({ name: 'plugin', status: 'warn', detail: expect.stringContaining('could not compare') });
  });
});
