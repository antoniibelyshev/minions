// plan (argv, env, files, config.toml), the strict output schema, result normalization and the JSONL usage parser.
// Never starts Codex.
import { describe, expect, it } from 'vitest';
import type { MinionsError } from '../../src/core/errors.js';
import { redact } from '../../src/core/output.js';
import { validateResult } from '../../src/runtime/results.js';
import { checkPlanEnv, type LaunchInput } from '../../src/runtime/runner/adapter.js';
import { PROCESS_ADAPTERS } from '../../src/runtime/runner/adapters.js';
import {
  CODEX_API_KEY_FILE, codexAdapter, codexConfigToml, codexOutputSchema, lastUsage, normalizeCodexResult, parseCodexEvent,
} from '../../src/runtime/runner/codex.js';

const S = '/scratch/lease-abc';
const SECRET = 'sk-proj-ThisMustNeverReachArgv0123456789';

function input(over: Partial<LaunchInput> = {}, contract: LaunchInput['role']['contract'] = 'gate'): LaunchInput {
  return {
    lease: { id: 'lease-abc', taskId: 'task-1', role: 'codex-reviewer', attempt: 1 },
    role: { name: 'codex-reviewer', contract, edits: 'none', commits: false },
    checkout: `${S}/work`, leaseWorktree: '/workspace/worktrees/task-1', gitObjectsDir: '/repo/.git/objects', scratchDir: S,
    harnessHome: `${S}/harness-home`, instructions: 'INSTRUCTIONS-BODY', briefFile: `${S}/brief.json`, resultFile: `${S}/result.json`,
    model: 'gpt-6.1-sol', effort: 'high', maxSteps: 50, credential: { kind: 'codex', file: `/secrets/${CODEX_API_KEY_FILE}` },
    ...over,
  };
}

const plan = (over: Partial<LaunchInput> = {}, contract: LaunchInput['role']['contract'] = 'gate') => codexAdapter().plan(input(over, contract));

describe('codex plan (gate)', () => {
  it('builds the exact codex exec argv; no secret, no --ask-for-approval', () => {
    const p = plan();
    expect(p.argv).toEqual([
      'codex', 'exec', '--json', '--ephemeral', '--strict-config', '--ignore-rules', '--color', 'never',
      '--cd', `${S}/work`, '--sandbox', 'danger-full-access', '--model', 'gpt-6.1-sol',
      '--output-schema', `${S}/codex/worker-result.schema.json`, '--output-last-message', `${S}/codex/last-message.json`, '-',
    ]);
    expect(p.argv).not.toContain('--ask-for-approval');
    expect(p.argv.join(' ')).not.toMatch(/sk-|KEY|INSTRUCTIONS-BODY/);
    // No model: no --model flag. A custom command prefix replaces argv[0] only.
    const q = codexAdapter({ command: ['/usr/bin/node', '/x/fake-codex.mjs'] }).plan(input({ model: null }));
    expect(q.argv.slice(0, 3)).toEqual(['/usr/bin/node', '/x/fake-codex.mjs', 'exec']);
    expect(q.argv).not.toContain('--model');
  });

  it('passes the key only through secretEnv, the prompt through stdin, and an env the runner accepts', () => {
    const p = plan();
    expect(p.secretEnv).toEqual({ CODEX_API_KEY: 'codex-api-key' });
    expect(p.env).toEqual({ CODEX_HOME: `${S}/harness-home`, NO_COLOR: '1', RUST_LOG: 'error' });
    expect(() => checkPlanEnv([...Object.keys(p.env), ...Object.keys(p.secretEnv)])).not.toThrow();
    expect(p.stdin).toContain('INSTRUCTIONS-BODY');
    expect(p.stdin).toMatch(/read-only gate/);
    expect(p.stdin).toMatch(/final message is your result/);
    expect(JSON.stringify(p)).not.toContain(SECRET);
  });

  it('writes only config.toml and the schema, inside the scratch dir, mode 0600', () => {
    const p = plan();
    expect(p.files.map((f) => f.path)).toEqual([`${S}/harness-home/config.toml`, `${S}/codex/worker-result.schema.json`]);
    for (const f of p.files) {
      expect(f.path.startsWith(`${S}/`)).toBe(true);
      expect(f.mode).toBe(0o600);
    }
    expect(JSON.parse(p.files[1]!.content)).toEqual(codexOutputSchema('gate'));
    expect(p.files[0]!.content).toBe(codexConfigToml(input()));
  });

  it('generates the exact config.toml', () => {
    expect(codexConfigToml(input())).toBe([
      '# Generated by minions for lease lease-abc (docs/design/agent-runtimes.md D6). The only user config this run loads.',
      'approval_policy = "never"',
      'sandbox_mode = "danger-full-access"',
      'web_search = "disabled"',
      'check_for_update_on_startup = false',
      'model_reasoning_effort = "high"',
      '',
      '[analytics]',
      'enabled = false',
      '',
      '[feedback]',
      'enabled = false',
      '',
      '[history]',
      'persistence = "none"',
      '',
      '# Commands Codex spawns get the core variables only, never *KEY* / *SECRET* / *TOKEN* (CODEX_API_KEY included).',
      '[shell_environment_policy]',
      'inherit = "core"',
      'ignore_default_excludes = false',
      '',
      '[shell_environment_policy.set]',
      'MINIONS_WORKER_LEASE = "lease-abc"',
      'MINIONS_ROLE = "codex-reviewer"',
      `MINIONS_BRIEF_FILE = "${S}/brief.json"`,
      `MINIONS_RESULT_FILE = "${S}/result.json"`,
      '',
      '# No repository-provided .codex/ config, hooks or rules.',
      `[projects."${S}/work"]`,
      'trust_level = "untrusted"',
      '',
    ].join('\n'));
  });

  it('escapes odd checkout paths as TOML basic strings and omits the effort when none is set', () => {
    const odd = '/scr "q"\\back\nline]=x';
    const t = codexConfigToml(input({ checkout: odd, effort: null }));
    expect(t).toContain('[projects."/scr \\"q\\"\\\\back\\nline]=x"]');
    expect(t).not.toContain('model_reasoning_effort');
    // No raw newline from the path leaks into the TOML structure.
    expect(t.split('\n').filter((l) => l.startsWith('line]'))).toEqual([]);
  });

  it('refuses producer and verifier roles until their plans land', () => {
    for (const c of ['producer', 'verifier'] as const) {
      let e: MinionsError | undefined;
      try { plan({}, c); } catch (x) { e = x as MinionsError; }
      expect(e?.code).toBe('PRECONDITION');
      expect(e?.message).toMatch(new RegExp(`no plan for ${c} roles`));
      expect(e?.hint).toMatch(/harness to claude/);
    }
  });

  it('only codex is registered in production; an empty command is refused', () => {
    expect(Object.keys(PROCESS_ADAPTERS)).toEqual(['codex']);
    expect(PROCESS_ADAPTERS.codex!.id).toBe('codex');
    expect(() => codexAdapter({ command: [] })).toThrow(/empty command/);
  });
});

/** Strict-mode compatibility (OpenAI structured outputs): every object closed and all its keys required. */
function walkStrict(node: unknown, path = '$'): string[] {
  if (!node || typeof node !== 'object') return [];
  const n = node as Record<string, unknown>;
  const out: string[] = [];
  if (n.type === 'object' || (Array.isArray(n.type) && n.type.includes('object'))) {
    const props = Object.keys((n.properties ?? {}) as object);
    if (n.additionalProperties !== false) out.push(`${path}: additionalProperties must be false`);
    if (JSON.stringify([...(n.required as string[] ?? [])].sort()) !== JSON.stringify([...props].sort())) out.push(`${path}: required must list every property`);
    for (const k of props) out.push(...walkStrict((n.properties as Record<string, unknown>)[k], `${path}.${k}`));
  }
  if (n.items) out.push(...walkStrict(n.items, `${path}[]`));
  return out;
}

describe('codex output schema', () => {
  it('is strict-mode compatible for every contract', () => {
    for (const c of ['gate', 'verifier', 'producer'] as const) expect(walkStrict(codexOutputSchema(c))).toEqual([]);
  });

  it('has the WorkerResult fields; verdict and needsQa only for a gate; no usage', () => {
    const g = codexOutputSchema('gate') as { properties: Record<string, { enum?: unknown[] }> };
    expect(Object.keys(g.properties)).toEqual(['status', 'summary', 'branch', 'headSha', 'modifiedPaths', 'checks', 'acceptanceEvidence', 'findings', 'nextAction', 'verdict', 'needsQa']);
    expect(g.properties.status!.enum).toEqual(['complete', 'needs_changes', 'blocked', 'needs_split', 'partial']);
    expect(g.properties.verdict!.enum).toEqual(['approve', 'request-changes', null]);
    const p = codexOutputSchema('producer') as { properties: Record<string, unknown> };
    expect(p.properties).not.toHaveProperty('verdict');
    expect(p.properties).not.toHaveProperty('usage');
    const pc = (p.properties.checks as { items: { properties: object } }).items.properties;
    expect(pc).not.toHaveProperty('source');
  });

  it('a schema-conformant final message with nulls normalizes to a valid gate WorkerResult', () => {
    const msg = {
      status: 'complete', summary: 'Looks good.', branch: 'agent/task-1', headSha: 'a'.repeat(40), modifiedPaths: [],
      checks: [{ command: 'npm test', outcome: 'pass', details: null, source: null }, { command: 'npm run typecheck', outcome: 'pass', details: 'ok', source: 'local' }],
      acceptanceEvidence: [{ criterion: 'works', evidence: 'test' }], findings: [], nextAction: 'merge', verdict: 'approve', needsQa: null,
    };
    expect(validateResult(JSON.stringify(msg), 'gate').ok).toBe(false);
    const norm = JSON.parse(normalizeCodexResult(JSON.stringify(msg))) as Record<string, unknown> & { checks: Record<string, unknown>[] };
    expect(norm).not.toHaveProperty('needsQa');
    expect(norm.checks[0]).toEqual({ command: 'npm test', outcome: 'pass' });
    expect(norm.checks[1]).toEqual({ command: 'npm run typecheck', outcome: 'pass', details: 'ok', source: 'local' });
    expect(validateResult(JSON.stringify(norm), 'gate')).toMatchObject({ ok: true });
  });

  it('leaves non-object text unchanged for the runner to judge', () => {
    for (const t of ['not json', '[1,2]', 'null', '42']) expect(normalizeCodexResult(t)).toBe(t);
  });
});

describe('codex JSONL parser', () => {
  // Shapes as printed by `codex exec --json` (exec/src/exec_events.rs, 0.164).
  const lines = [
    '{"type":"thread.started","thread_id":"0199a213-81c0-7800-8aa1-bbab2a035a53"}',
    '{"type":"turn.started"}',
    '{"type":"item.completed","item":{"id":"item_0","type":"reasoning","text":"**Reviewing**"}}',
    '{"type":"item.completed","item":{"id":"item_1","type":"command_execution","command":"bash -lc ls","aggregated_output":"a\\n","exit_code":0,"status":"completed"}}',
    '{"type":"item.completed","item":{"id":"item_2","type":"agent_message","text":"{\\"status\\":\\"complete\\",\\"verdict\\":\\"approve\\",\\"needsQa\\":null}"}}',
    '{"type":"turn.completed","usage":{"input_tokens":24763,"cached_input_tokens":24448,"output_tokens":122}}',
  ];

  it('extracts the final message (normalized) and the usage; ignores other events', () => {
    const ev = lines.map(parseCodexEvent);
    expect(ev.slice(0, 4)).toEqual([null, null, null, null]);
    expect(ev[4]).toEqual({ finalMessage: '{"status":"complete","verdict":"approve"}' });
    expect(ev[5]).toEqual({ usage: { inputTokens: 24763, outputTokens: 122, cachedInputTokens: 24448 } });
  });

  it('ignores malformed, negative, non-numeric and non-JSON input', () => {
    for (const l of [
      '', 'plain log line', '{not json', '[1]', '{"type":"turn.completed"}', '{"type":"turn.completed","usage":null}',
      '{"type":"turn.completed","usage":{"input_tokens":-1,"output_tokens":3}}',
      '{"type":"turn.completed","usage":{"input_tokens":"10","output_tokens":3}}',
      '{"type":"turn.completed","usage":{"input_tokens":10}}',
      '{"type":"item.completed","item":{"type":"agent_message","text":7}}',
      '{"type":"item.completed","item":{"type":"reasoning","text":"x"}}',
      '{"type":"turn.failed","error":{"message":"boom"}}',
    ]) expect(parseCodexEvent(l)).toBeNull();
    // A zero or invalid cached count is dropped, not an error; fractions are floored.
    expect(parseCodexEvent('{"type":"turn.completed","usage":{"input_tokens":10.7,"output_tokens":2,"cached_input_tokens":-5}}'))
      .toEqual({ usage: { inputTokens: 10, outputTokens: 2 } });
  });

  it('final usage is the last turn.completed running total, not a sum', () => {
    const ev = [{ inputTokens: 100, outputTokens: 10, cachedInputTokens: 50 }, { inputTokens: 300, outputTokens: 40, cachedInputTokens: 200 }];
    expect(lastUsage(ev)).toEqual({ tokens: 340, detail: { inputTokens: 300, outputTokens: 40, cachedInputTokens: 200 } });
    expect(lastUsage([{ inputTokens: 5, outputTokens: 1 }])).toEqual({ tokens: 6, detail: { inputTokens: 5, outputTokens: 1, cachedInputTokens: 0 } });
    expect(lastUsage([])).toBeNull();
    expect(codexAdapter().finalUsage).toBe(lastUsage);
  });

  it('redact masks OpenAI keys (the codex credential)', () => {
    expect(redact(`key=${SECRET} done`)).toBe('key=sk-[REDACTED] done');
    expect(redact('sk-ant-abcdefgh12345')).toBe('sk-ant-[REDACTED]');
  });
});
